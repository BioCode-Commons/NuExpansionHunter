// Writes harness/tables.h: the lookup tables that the proved kernels read, taken from the product and htslib
// headers, so that the proofs use exactly the product's data. run_proofs.sh regenerates the file and fails if
// it differs from the committed copy.
#include <cctype>
#include <cstdio>

#include "htslib/hts.h"
#include "graphutils/BaseMatching.hh"

static void table(const char* name, const unsigned char* values, int count)
{
    std::printf("static const unsigned char %s[%d] = {", name, count);
    for (int i = 0; i < count; ++i)
        std::printf("%s%u", i == 0 ? "\n    " : i % 16 ? ", " : ",\n    ", unsigned(values[i]));
    std::printf("\n};\n");
}

int main()
{
    std::printf("// Generated by scripts/gen_tables.cpp from htslib and graphutils/BaseMatching.hh. Do not edit.\n");
    std::printf("#pragma once\n");
    table("hts_nt16_table", seq_nt16_table, 256);
    unsigned char upper[17] = {}, lower[17] = {};
    for (int i = 0; i < 16; ++i)
    {
        upper[i] = (unsigned char)seq_nt16_str[i];
        lower[i] = (unsigned char)std::tolower(seq_nt16_str[i]);
    }
    table("hts_nt16_upper", upper, 16);
    table("hts_nt16_lower", lower, 16);
    table("gt_reference_codes", graphtools::codes::kReferenceBaseEncodingTable.data(), 256);
    table("gt_query_codes", graphtools::codes::kQueryBaseEncodingTable.data(), 256);
    unsigned char match[16 * 5];
    for (int r = 0; r < 16; ++r)
        for (int q = 0; q < 5; ++q)
            match[r * 5 + q] = graphtools::codes::kReferenceQueryCodeMatchLookupTable[r][q];
    table("gt_code_match", match, 80);
    return 0;
}
